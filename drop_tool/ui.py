"""ウィジェット構成。監視・保存・画像認識はAppのイベントへ委譲する。"""
import tkinter as tk
from tkinter import ttk
from .karen_banner import KarenBanner
from .scrollable import ScrollablePane
from .csv_views import CsvViews

def build_widgets(self):
    """画面の構築だけを担当する。保存やCSV生成は専用モジュールに任せる。"""
    root = self.root
    self.page = ScrollablePane(root, minimum_width=980, minimum_height=730)
    self.page.pack(fill="both", expand=True)
    pane = ttk.Frame(self.page.content, padding=10)
    pane.pack(fill='both', expand=True)
    bar = ttk.Frame(pane)
    bar.pack(fill='x')
    ttk.Label(bar, text='撮影するゲーム：').pack(side='left')
    self.window = ttk.Combobox(bar, state='readonly', width=62)
    self.window.pack(side='left', fill='x', expand=True)
    ttk.Button(bar, text='一覧更新', command=self.refresh_windows).pack(side='left', padx=5)
    self.window.bind('<<ComboboxSelected>>', self.choose_window)
    identity = ttk.Frame(pane)
    identity.pack(fill='x', pady=(6, 0))
    ttk.Label(identity, text='プレイヤー名（CSVに表示）：').pack(side='left')
    player_entry = ttk.Entry(identity, textvariable=self.player_name, width=28)
    player_entry.pack(side='left')
    player_entry.bind('<FocusOut>', lambda event: self.save_player_name())
    ttk.Button(identity, text='名前を保存', command=self.save_player_name).pack(side='left', padx=5)
    bar = ttk.Frame(pane)
    bar.pack(fill='x', pady=8)
    self.dungeon = ttk.Combobox(bar, values=['アルビ', 'キア', 'ラビ', '夢幻ラビ', 'マス', 'フィアード', 'バリ', 'ルンダ', 'ペッカ'], width=15)
    self.dungeon.set('アルビ')
    self.dungeon.pack(side='left')
    self.difficulty = ttk.Combobox(bar, values=['通常', '初級', '中級', '上級', 'HD', '誘惑', '音楽'], width=12)
    self.difficulty.set('HD')
    self.difficulty.pack(side='left', padx=4)
    ttk.Label(bar, text='ネアル：').pack(side='left')
    self.near = ttk.Combobox(bar, values=['使用', '不使用', '未指定'], state='readonly', width=8)
    self.near.set('使用')
    self.near.pack(side='left')
    for widget in (self.dungeon, self.difficulty):
        widget.bind('<<ComboboxSelected>>', self.context_changed)
        widget.bind('<FocusOut>', self.context_changed)
    ttk.Button(bar, text='入場：新しい周回', command=self.new_run, style='Accent.TButton').pack(side='left', padx=8)
    ttk.Button(bar, text='監視停止', command=self.stop).pack(side='left')
    ttk.Button(bar, text='監視再開', command=self.resume).pack(side='left')
    notes_row = ttk.Frame(pane)
    notes_row.pack(fill='x', pady=(3, 0))
    self.banner = KarenBanner(notes_row, self.timed_read)
    self.banner.pack(side='right', anchor='n', padx=(8, 0))
    notes = ttk.Frame(notes_row)
    notes.pack(side='left', fill='both', expand=True)
    ttk.Label(notes, text='報酬をALT表示 → 読取完了 → 履歴で確認・確定', wraplength=580).pack(anchor='w')
    ttk.Label(notes, textvariable=self.status, wraplength=560).pack(fill='x', pady=6)
    ttk.Label(notes, textvariable=self.diagnostic, wraplength=560).pack(fill='x')
    sound_bar = ttk.Frame(notes)
    sound_bar.pack(anchor='w')
    ttk.Checkbutton(sound_bar, text='読取完了音', variable=self.sound_enabled,
                    command=self.change_sound).pack(side='left')
    ttk.Button(sound_bar, text='試聴', command=lambda: self.completion_sound.play(preview=True)).pack(side='left', padx=6)
    actions = ttk.Frame(pane)
    actions.pack(fill='x')
    ttk.Label(actions, text='画面の品名を自動検出').pack(side='left')
    ttk.Button(actions, text='画像で動作確認（統計に入れない）', command=self.test_image).pack(side='left', padx=5)
    ttk.Button(actions, text='CSV出力', command=self.export).pack(side='right')
    notebook = ttk.Notebook(pane)
    self.notebook = notebook
    notebook.pack(fill='both', expand=True, pady=8)
    stats = ttk.Frame(notebook, padding=8)
    review = ttk.Frame(notebook, padding=8)
    notebook.add(stats, text='ドロップ統計')
    notebook.add(review, text='周回履歴・確認待ち')
    self.csv_views = CsvViews(notebook, self.store.folder)
    ttk.Label(stats, textvariable=self.summary, wraplength=950).pack(anchor='w', pady=5)
    self.groups = ttk.Combobox(stats, state='readonly', width=60)
    self.groups.pack(anchor='w')
    self.groups.bind('<<ComboboxSelected>>', lambda e: self.refresh_stats())
    self.stats_table = ttk.Treeview(stats, columns=('name', 'hits', 'rate'), show='headings', height=9)
    for key, text, width in [('name', 'アイテム', 430), ('hits', '出現した周回数', 180), ('rate', '出現率（記録できた周回内）', 250)]:
        self.stats_table.heading(key, text=text)
        self.stats_table.column(key, width=width)
    self.stats_table.pack(fill='both', expand=True, pady=8)
    ttk.Label(stats, text='数量・宝箱1個あたりの確率ではなく、1周の報酬にその品が含まれた割合です。\n未取得・確認待ちは分母に含めません。偏りを避けるため、確認待ちを解消してから比較してください。', wraplength=950).pack(anchor='w')
    run_frame = ttk.Frame(review)
    run_frame.pack(fill='x')
    self.runs = ttk.Treeview(run_frame, columns=('date', 'context', 'status'), show='headings', height=2)
    for key, text, width in [('date', '入場記録時刻', 230), ('context', 'ダンジョン / 難易度 / ネアル', 460), ('status', '状態', 150)]:
        self.runs.heading(key, text=text)
        self.runs.column(key, width=width)
    run_scroll = ttk.Scrollbar(run_frame, orient='vertical', command=self.runs.yview)
    run_scroll.pack(side='right', fill='y')
    self.runs.configure(yscrollcommand=run_scroll.set)
    self.runs.pack(in_=run_frame, side='left', fill='both', expand=True)
    self.runs.bind('<<TreeviewSelect>>', self.select_run)
    rows_frame = ttk.Frame(review)
    rows_frame.pack(fill='both', expand=True, pady=6)
    self.rows = ttk.Treeview(rows_frame, columns=('name', 'kind'), show='headings', height=2)
    self.rows.heading('name', text='読み取った品名')
    self.rows.column('name', width=680)
    self.rows.heading('kind', text='扱い')
    self.rows.column('kind', width=140)
    rows_scroll = ttk.Scrollbar(rows_frame, orient='vertical', command=self.rows.yview)
    rows_scroll.pack(side='right', fill='y')
    self.rows.configure(yscrollcommand=rows_scroll.set)
    self.rows.pack(in_=rows_frame, side='left', fill='both', expand=True)
    self.rows.bind('<<TreeviewSelect>>', self.select_row)
    self.clean_preview = tk.BooleanVar(value=False)
    ttk.Checkbutton(review, text='白黒表示で比較（通常は元のカラー表示）', variable=self.clean_preview, command=self.select_row).pack(anchor='w')
    self.preview = ttk.Label(review)
    self.preview.pack(anchor='w')
    row = ttk.Frame(review)
    row.pack(fill='x', pady=6)
    self.correct = tk.StringVar()
    ttk.Entry(row, textvariable=self.correct, width=48).pack(side='left')
    ttk.Button(row, text='この名前で集計・学習', command=lambda: self.correct_row('material')).pack(side='left', padx=4)
    ttk.Button(row, text='除外・学習', command=lambda: self.correct_row('excluded')).pack(side='left')
    row = ttk.Frame(review)
    row.pack(fill='x')
    ttk.Button(row, text='修正した周回を確定', command=self.confirm_run).pack(side='left')
    ttk.Button(row, text='この周回を集計対象外にする', command=self.discard).pack(side='left', padx=6)
    ttk.Button(row, text='選択した周回を削除', command=self.delete_runs).pack(side='left', padx=6)
